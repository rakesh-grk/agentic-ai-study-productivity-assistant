import json
import logging
from typing import Optional, Dict, Any
import requests
from core.configuration import AppConfig

logger = logging.getLogger("LLMClient")

class LLMClient:
    """Configurable client for interacting with LLM providers (Gemini, OpenAI, Anthropic)

    or operating in offline deterministic mode.
    """
    
    def __init__(self, provider: Optional[str] = None, force_offline: bool = False):
        self.provider = (provider or AppConfig.LLM_PROVIDER).lower()
        self.force_offline = force_offline
        self.timeout = 25  # seconds
        
    @property
    def is_offline(self) -> bool:
        if self.force_offline:
            return True
        return not AppConfig.is_api_configured(self.provider)

    def generate(self, prompt: str, system_prompt: str = "", json_mode: bool = False) -> str:
        """Dispatches prompt to configured provider or fallback offline generator."""
        if self.is_offline:
            return self._offline_response(prompt, json_mode)
            
        try:
            if self.provider == "gemini":
                return self._call_gemini(prompt, system_prompt, json_mode)
            elif self.provider == "openai":
                return self._call_openai(prompt, system_prompt, json_mode)
            elif self.provider == "anthropic":
                return self._call_anthropic(prompt, system_prompt)
            else:
                return self._offline_response(prompt, json_mode)
        except Exception as e:
            logger.warning(f"Provider {self.provider} failed: {e}. Falling back to offline demonstration mode.")
            return self._offline_response(prompt, json_mode, error_note=str(e))

    def _call_gemini(self, prompt: str, system_prompt: str, json_mode: bool) -> str:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{AppConfig.GEMINI_MODEL}:generateContent?key={AppConfig.GEMINI_API_KEY}"
        contents = []
        if system_prompt:
            contents.append({"role": "user", "parts": [{"text": f"SYSTEM INSTRUCTION: {system_prompt}"}]})
            contents.append({"role": "model", "parts": [{"text": "Understood."}]})
        contents.append({"role": "user", "parts": [{"text": prompt}]})
        
        body: Dict[str, Any] = {"contents": contents}
        if json_mode:
            body["generationConfig"] = {"responseMimeType": "application/json"}
            
        resp = requests.post(url, json=body, timeout=self.timeout)
        resp.raise_for_status()
        data = resp.json()
        return data["candidates"][0]["content"]["parts"][0]["text"]

    def _call_openai(self, prompt: str, system_prompt: str, json_mode: bool) -> str:
        url = "https://api.openai.com/v1/chat/completions"
        headers = {
            "Authorization": f"Bearer {AppConfig.OPENAI_API_KEY}",
            "Content-Type": "application/json"
        }
        messages = []
        if system_prompt:
            messages.append({"role": "system", "content": system_prompt})
        messages.append({"role": "user", "content": prompt})
        
        payload: Dict[str, Any] = {
            "model": AppConfig.OPENAI_MODEL,
            "messages": messages,
            "temperature": 0.3
        }
        if json_mode:
            payload["response_format"] = {"type": "json_object"}
            
        resp = requests.post(url, headers=headers, json=payload, timeout=self.timeout)
        resp.raise_for_status()
        data = resp.json()
        return data["choices"][0]["message"]["content"]

    def _call_anthropic(self, prompt: str, system_prompt: str) -> str:
        url = "https://api.anthropic.com/v1/messages"
        headers = {
            "x-api-key": AppConfig.ANTHROPIC_API_KEY,
            "anthropic-version": "2023-06-01",
            "content-type": "application/json"
        }
        payload = {
            "model": AppConfig.ANTHROPIC_MODEL,
            "max_tokens": 1500,
            "system": system_prompt or "You are an agentic AI assistant.",
            "messages": [{"role": "user", "content": prompt}]
        }
        resp = requests.post(url, headers=headers, json=payload, timeout=self.timeout)
        resp.raise_for_status()
        data = resp.json()
        return data["content"][0]["text"]

    def _offline_response(self, prompt: str, json_mode: bool, error_note: Optional[str] = None) -> str:
        """Deterministic, clearly labeled offline demonstration behavior."""
        if json_mode:
            # Provide clean fallback JSON for structured agent outputs
            return json.dumps({
                "mode": "offline_demonstration",
                "notice": "Offline mode active (Deterministic demonstration without live LLM API).",
                "content": "Demonstration output generated by offline agent pipeline."
            })
        return "[OFFLINE DEMO MODE] This output was generated by the local rule-based agent pipeline."
